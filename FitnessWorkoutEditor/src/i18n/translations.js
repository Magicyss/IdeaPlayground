// Get browser language
export function getBrowserLanguage() {
  const browserLang = navigator.language || navigator.userLanguage;
  // Check if it's Chinese (zh, zh-CN, zh-TW, etc.)
  if (browserLang.toLowerCase().startsWith("zh")) {
    return "zh";
  }
  return "en";
}
